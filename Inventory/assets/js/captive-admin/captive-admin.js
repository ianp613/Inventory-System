(function(){

  // In-memory store only — this demonstrates the UI and code generation.
  // To persist vouchers and actually grant access, POST each voucher to
  // your backend, which should create it on the UniFi Controller
  // (Settings > Guest Control / the Hotspot Manager API) using the same
  // fields collected here, then store the returned voucher record.
  var vouchers = [];
  var currentPage = 1;
  var rowsPerPage = 9;

  var form = document.getElementById('voucherForm');
  var formMsg = document.getElementById('formMsg');
  var tbody = document.getElementById('voucherBody');
  var searchBox = document.getElementById('searchBox');
  var toast = document.getElementById('toast');
  var exportBtn = document.getElementById('exportBtn');
  var clock = document.getElementById('clock');

  // Voucher codes are generated by create_voucher.php on the server now —
  // no client-side code generation needed.

  function showToast(msg){
    toast.textContent = msg;
    toast.classList.add('show');
    setTimeout(function(){ toast.classList.remove('show'); }, 1800);
  }

  function formatDate(d){
    return d.toLocaleDateString(undefined,{ month:'short', day:'numeric' }) + ' · ' +
           d.toLocaleTimeString(undefined,{ hour:'2-digit', minute:'2-digit' });
  }

  function badge(status){
    var map = { active:'Active', used:'Used up', revoked:'Revoked' };
    return '<span class="badge ' + status + '"><span class="dot"></span>' + map[status] + '</span>';
  }

  // Builds a page-number list with ellipses, e.g. for 12 pages on page 6:
  // [1, '...', 5, 6, 7, '...', 12]. Always keeps first, last, and a
  // window of 1 page on either side of the current page.
  function buildPageList(current, total){
    var delta = 1;
    var range = [];
    var withDots = [];
    var i;

    for(i = 1; i <= total; i++){
      if(i === 1 || i === total || (i >= current - delta && i <= current + delta)){
        range.push(i);
      }
    }

    var last = null;
    for(i = 0; i < range.length; i++){
      var page = range[i];
      if(last !== null){
        if(page - last === 2){
          withDots.push(last + 1);
        } else if(page - last > 2){
          withDots.push('...');
        }
      }
      withDots.push(page);
      last = page;
    }
    return withDots;
  }

  function render(){
    var query = searchBox.value.trim().toLowerCase();
    var filtered = vouchers.filter(function(v){
      return !query || v.code.toLowerCase().indexOf(query) > -1 || v.name.toLowerCase().indexOf(query) > -1;
    });

    var totalPages = Math.max(Math.ceil(filtered.length / rowsPerPage), 1);
    if(currentPage > totalPages) currentPage = totalPages;
    if(currentPage < 1) currentPage = 1;

    var start = (currentPage - 1) * rowsPerPage;
    var pageItems = filtered.slice(start, start + rowsPerPage);

    if(pageItems.length === 0){
      tbody.innerHTML = '<tr class="empty-row"><td colspan="9">' +
        (vouchers.length === 0 ? 'No vouchers yet — create one on the left to get started.' : 'No vouchers match your search.') +
        '</td></tr>';
    } else {
      tbody.innerHTML = pageItems.map(function(v){
        return '<tr>' +
          '<td><div class="code-cell"><span class="code">' + v.code + '</span>' +
            '<button class="copy-btn" data-code="' + v.code + '" title="Copy code">' +
            '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"><rect x="7" y="7" width="10" height="10" rx="2"/><path d="M4.5 13.5H4a1 1 0 0 1-1-1V4a1 1 0 0 1 1-1h8.5a1 1 0 0 1 1 1v.5"/></svg>' +
            '</button></div></td>' +
          '<td>' + v.name + '</td>' +
          '<td class="mono">' + v.duration + ' ' + v.durationUnit + '</td>' +
          '<td class="mono">' + (parseInt(v.usesRemaining) === 0 ? '∞' : v.usesRemaining) + (parseInt(v.uses) === 0 ? ' / ∞' : ' / ' + v.uses) + '</td>' +
          '<td>' + badge(v.status) + '</td>' +
          '<td class="muted-cell">' + formatDate(v.created) + '</td>' +
          '<td>' + (v.status === 'revoked' ? '' : '<button class="revoke-btn" data-id="' + v.id + '">Revoke</button>') + '</td>' +
        '</tr>';
      }).join('');
    }

    document.getElementById('statTotal').textContent = vouchers.length;
    document.getElementById('statActive').textContent = vouchers.filter(function(v){ return v.status==='active'; }).length;
    document.getElementById('statUsed').textContent = vouchers.filter(function(v){ return v.status==='used'; }).length;
    document.getElementById('statRevoked').textContent = vouchers.filter(function(v){ return v.status==='revoked'; }).length;

    renderPagination(filtered.length, totalPages, start, pageItems.length);
  }

  function renderPagination(filteredCount, totalPages, start, shownCount){
    var rangeLabel = filteredCount === 0 ? '0' : (start + 1) + '–' + (start + shownCount);
    document.getElementById('pageRangeLabel').textContent = rangeLabel;
    document.getElementById('pageTotalLabel').textContent = filteredCount;

    var controls = document.getElementById('pageControls');
    var pages = buildPageList(currentPage, totalPages);
    var html = '';

    html += '<button class="page-btn" id="prevPage" ' + (currentPage === 1 ? 'disabled' : '') + ' aria-label="Previous page">' +
      '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M12.5 15 7.5 10l5-5"/></svg></button>';

    pages.forEach(function(p){
      if(p === '...'){
        html += '<span class="page-ellipsis">…</span>';
      } else {
        html += '<button class="page-btn' + (p === currentPage ? ' active' : '') + '" data-page="' + p + '">' + p + '</button>';
      }
    });

    html += '<button class="page-btn" id="nextPage" ' + (currentPage === totalPages ? 'disabled' : '') + ' aria-label="Next page">' +
      '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M7.5 15l5-5-5-5"/></svg></button>';

    controls.innerHTML = html;

    var prevBtn = document.getElementById('prevPage');
    var nextBtn = document.getElementById('nextPage');
    if(prevBtn) prevBtn.addEventListener('click', function(){ currentPage--; render(); });
    if(nextBtn) nextBtn.addEventListener('click', function(){ currentPage++; render(); });
    controls.querySelectorAll('[data-page]').forEach(function(btn){
      btn.addEventListener('click', function(){ currentPage = parseInt(btn.getAttribute('data-page'), 10); render(); });
    });
  }

  form.addEventListener('submit', function(e){
    e.preventDefault();

    var payload = {
      voucher_name: document.getElementById('vName').value.trim() || 'Guest',
      count: Math.min(Math.max(parseInt(document.getElementById('vCount').value, 10) || 1, 1), 500),
      duration: parseInt(document.getElementById('vDuration').value, 10) || 1,
      duration_unit: document.getElementById('vDurationUnit').value,
      uses: parseInt(document.getElementById('vUses').value, 10) || 0
    };

    var submitBtn = form.querySelector('button.generate');
    submitBtn.disabled = true;

    // "count" isn't a column on the voucher table itself — it just tells
    // create_voucher.php how many rows to insert in this batch. Every other
    // key here matches your $fillable list, so `code`, `uses_remaining`,
    // `status`, `id`, `created_at`/`updated_at` are all set server-side.
    sole.post("../../controllers/captive-admin/create_voucher.php", payload)
      .then(function(res){
        submitBtn.disabled = false;
        if(res.status){
          formMsg.textContent = payload.count === 1 ? '1 voucher created.' : payload.count + ' vouchers created.';
          formMsg.classList.add('show');
          setTimeout(function(){ formMsg.classList.remove('show'); }, 2500);
          form.reset();
          document.getElementById('vCount').value = 1;
          document.getElementById('vUses').value = 1;
          currentPage = 1;
          loadVouchers();
        } else {
          showToast(res.message || 'Could not create voucher.');
        }
      })
      .catch(function(e){
        submitBtn.disabled = false;
        showToast('Request failed. Check your connection.');
      });
  });

  function loadVouchers(){
    // NOTE: point this at whatever endpoint returns your voucher list
    // (e.g. list_vouchers.php). Assumes a JSON response shaped like
    // { status: true, data: [ {...one row per your $fillable columns...} ] }.
    sole.get("../../controllers/captive-admin/list_vouchers.php")
      .then(function(res){
        if(!res.status){ showToast(res.message || 'Could not load vouchers.'); return; }

        vouchers = (res.data || []).map(function(row){
          return {
            id: row.id,
            code: row.code,
            name: row.voucher_name || 'Guest',
            duration: row.duration,
            durationUnit: row.duration_unit,
            uses: row.uses,
            usesRemaining: row.uses_remaining,
            status: row.status,
            created: row.created_at ? new Date(row.created_at) : new Date()
          };
        });

        render();
      })
      .catch(function(){
        showToast('Could not reach the server.');
      });
  }

  tbody.addEventListener('click', function(e){
    var copyBtn = e.target.closest('.copy-btn');
    if(copyBtn){
      var code = copyBtn.getAttribute('data-code');
      if(navigator.clipboard){
        navigator.clipboard.writeText(code).then(function(){ showToast('Copied ' + code); });
      } else {
        showToast(code);
      }
      return;
    }
    var revokeBtn = e.target.closest('.revoke-btn');
    if(revokeBtn){
      var id = revokeBtn.getAttribute('data-id');
      // NOTE: point this at your revoke/delete endpoint. Adjust the
      // payload key ("id") if your PHP expects something else.
      sole.post("../../controllers/captive-admin/revoke_voucher.php", { id: id })
        .then(function(res){
          if(res.status){
            showToast('Voucher revoked');
            loadVouchers();
          } else {
            showToast(res.message || 'Could not revoke voucher.');
          }
        })
        .catch(function(){
          showToast('Request failed. Check your connection.');
        });
    }
  });

  searchBox.addEventListener('input', function(){ currentPage = 1; render(); });

  exportBtn.addEventListener('click', function(){
    if(vouchers.length === 0){ showToast('No vouchers to export'); return; }
    var header = ['Code','Voucher/Username','Duration','Duration Unit','Uses Allowed','Uses Remaining','Data Limit (MB)','Data Cap (MB)','Status','Created'];
    var rows = vouchers.map(function(v){
      return [v.code, v.name, v.duration, v.durationUnit, v.uses, v.usesRemaining, v.dataLimit, v.dataCap, v.status, v.created.toISOString()];
    });
    var csv = [header].concat(rows).map(function(r){
      return r.map(function(cell){ return '"' + String(cell).replace(/"/g,'""') + '"'; }).join(',');
    }).join('\n');
    var blob = new Blob([csv], { type:'text/csv' });
    var a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'vouchers.csv';
    a.click();
  });

  function tickClock(){
    clock.textContent = new Date().toLocaleString(undefined,{ weekday:'short', month:'short', day:'numeric', hour:'2-digit', minute:'2-digit' });
  }
  tickClock();
  setInterval(tickClock, 30000);
  document.getElementById('year').textContent = new Date().getFullYear();

  loadVouchers();

})();