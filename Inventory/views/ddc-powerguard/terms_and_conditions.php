    <div class="toc-section-header">
      <div class="toc-section-num">02</div>
      <div class="toc-section-title">System Description</div>
    </div>
    <p>DDC Powerguard is an internal incident management system designed to streamline the reporting, assessment, and resolution of electrical fluctuation events affecting workstations and equipment within the organization. The System enables:</p>
    <ul>
      <li>Filing and tracking of electrical incident tickets by authorized supervisors</li>
      <li>Assignment and assessment of damaged workstation terminals by technicians</li>
      <li>Review, sign-off, and rejection of assessments by supervisors</li>
      <li>Department and account management by administrators</li>
      <li>Generation of reports across all incident records</li>
    </ul>
  </div>

