  <div class="toc-section" id="s3">
    <div class="toc-section-header">
      <div class="toc-section-num">03</div>
      <div class="toc-section-title">User Roles and Responsibilities</div>
    </div>
    <p>Access to the System is role-based. Each role carries distinct permissions and obligations:</p>

    <div class="toc-role-block">
      <div class="toc-role-title">
        Administrator
        <span class="toc-role-badge toc-badge-amber">Full access</span>
      </div>
      <ul>
        <li>Manage user accounts — create technician accounts, approve or reject supervisor registrations</li>
        <li>Create, assign, and delete departments; assign supervisors to departments</li>
        <li>Oversee all incident tickets across all departments without submitting new ones</li>
        <li>Reassign workstation terminals between technicians</li>
        <li>Access system-wide reports across all incidents and projects</li>
      </ul>
    </div>

    <div class="toc-role-block">
      <div class="toc-role-title">
        Supervisor / Operations Manager
        <span class="toc-role-badge toc-badge-blue">Department scope</span>
      </div>
      <ul>
        <li>Submit incident tickets for their assigned department only</li>
        <li>Declare workstation damage at the time of ticket submission</li>
        <li>Review and sign off or reject technician assessments</li>
        <li>View status and reports for their own submitted tickets only</li>
        <li>A supervisor may be assigned to multiple departments simultaneously</li>
      </ul>
    </div>

    <div class="toc-role-block">
      <div class="toc-role-title">
        Technician
        <span class="toc-role-badge toc-badge-green">Assessment scope</span>
      </div>
      <ul>
        <li>View all submitted incident tickets across all departments</li>
        <li>Self-assign (claim) unclaimed workstation terminals within any ticket</li>
        <li>Submit assessments for claimed terminals, including component condition and findings</li>
        <li>Transfer claimed terminals to another technician with a stated reason</li>
        <li>View reports across all incidents and projects</li>
        <li>Technician accounts are created directly by the administrator — no self-registration</li>
      </ul>
    </div>
  </div>

